"""End-to-end click-through of Document Tracker against mock_server.py."""
import json, subprocess, sys, time, os, urllib.request, datetime
from playwright.sync_api import sync_playwright

HERE = os.path.dirname(os.path.abspath(__file__))
FX = os.path.join(HERE, "fixtures")
PORT = 8766
BASE = f"http://127.0.0.1:{PORT}/"
SHOTS = os.path.join(HERE, "shots"); os.makedirs(SHOTS, exist_ok=True)
srv = subprocess.Popen([sys.executable, os.path.join(HERE, "mock_server.py"), str(PORT)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1.0)
errors = []
today = datetime.date.today()
iso = lambda d: d.isoformat()
year = today.year


def calls(): return json.loads(urllib.request.urlopen(BASE + "calls").read())
def setpick(paths):
    req = urllib.request.Request(BASE + "setpick", data=json.dumps(paths).encode(), method="POST")
    urllib.request.urlopen(req).read()
def check(cond, msg):
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond: errors.append(msg)
def fx(n): return os.path.join(FX, n)


try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": 1366, "height": 860}); pg.set_default_timeout(8000)
        pg.on("console", lambda m: m.type == "error" and errors.append("console: " + m.text))
        pg.on("pageerror", lambda e: errors.append("pageerror: " + str(e)))
        pg.goto(BASE)
        pg.wait_for_selector("h1:has-text('Dashboard')")

        print("== settings", flush=True)
        pg.click("#nav button[data-view=settings]")
        pg.fill("input[name=company_name]", "Casas Development Corp.")
        pg.fill("input[name=doc_prefix]", "PMO")
        pg.fill("input[name=user_name]", "Jae")
        pg.click("#settings-form button[type=submit]")
        pg.wait_for_selector(".toast:has-text('Settings saved')")

        print("== simulate dropping 3 PDFs", flush=True)
        pg.click("#nav button[data-view=dashboard]")
        pg.evaluate("paths => { newDocuments(paths); }", [fx("Site Development Plan.pdf"), fx("Building Permit 2026.pdf"), fx("Contractor Billing No 3.pdf")])
        pg.wait_for_selector("#nd-rows tr >> nth=2")
        nos = pg.eval_on_selector_all("input[name='docno[]']", "els => els.map(e => e.value)")
        check(nos == [f"PMO-{year}-0001", f"PMO-{year}-0002", f"PMO-{year}-0003"], f"auto numbers {nos}")
        titles = pg.eval_on_selector_all("input[name='title[]']", "els => els.map(e => e.value)")
        check(titles[0] == "Site Development Plan", "title from file name")
        pg.fill(".modal input[name=project]", "Casas Phase 2")
        pg.select_option(".modal select[name=category]", "Plans / Drawings")
        pg.select_option(".modal select[name=action]", "For Approval")
        pg.fill(".modal input[name=location]", "Mr. Sabanal")
        pg.fill(".modal input[name=due_date]", iso(today - datetime.timedelta(days=2)))
        pg.fill(".modal input[name=remarks]", "For approval of Mr. Sabanal")
        pg.screenshot(path=f"{SHOTS}/01_new_docs.png")
        pg.click(".modal button[type=submit]")
        pg.wait_for_selector("h1:has-text('Documents')")
        pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 3, "3 documents created")
        check(pg.locator("#doc-table tr.overdue").count() == 3, "3 overdue rows")
        pg.screenshot(path=f"{SHOTS}/02_register.png")

        print("== open first doc and route: Approved -> Accounting", flush=True)
        pg.click(f"a.docno:has-text('PMO-{year}-0001')")
        pg.wait_for_selector(".now-box:has-text('Mr. Sabanal')")
        pg.click(".now-box button[data-act=route]")
        pg.click(".modal [data-quick='Approved']")
        pg.fill(".modal input[name=location]", "Accounting")
        pg.fill(".modal textarea[name=remarks]", "Approved by Mr. Sabanal, forwarded to Accounting")
        pg.screenshot(path=f"{SHOTS}/03_update_modal.png")
        pg.click(".modal button[type=submit]")
        pg.wait_for_selector(".now-box:has-text('Accounting')")
        check(pg.locator(".now-box.overdue").count() == 0, "no longer overdue after update (new due date)")
        check(pg.locator(".timeline tbody tr").count() == 3, "history: created + 2 routes")
        check("Mr. Sabanal" in pg.inner_text(".timeline tbody tr >> nth=0") and "Accounting" in pg.inner_text(".timeline tbody tr >> nth=0"), "history shows from -> to")

        print("== add revision", flush=True)
        setpick([fx("Site Development Plan Rev1.pdf")])
        pg.click("button[data-act=addRev]")
        pg.wait_for_selector(".modal-head:has-text('Add Revision')")
        check(pg.input_value(".modal input[name=rev]") == "1", "next revision suggested = 1")
        pg.click(".modal button[type=submit]")
        pg.wait_for_selector("text=superseded")
        check(pg.locator(".badge.teal:has-text('current')").count() == 1 and "1" in pg.inner_text("tr:has(.badge.teal) td >> nth=0"), "newest revision marked current")
        pg.locator("button[data-act=openFile]").first.click()
        pg.wait_for_timeout(200)
        pg.screenshot(path=f"{SHOTS}/04_doc_detail.png", full_page=True)

        print("== duplicate detection + paper document", flush=True)
        pg.click("#nav button[data-view=register]")
        pg.click("button:has-text('+ New Document')")
        pg.wait_for_selector("#nd-rows tr")
        setpick([fx("SDP copy.pdf")])
        pg.click("#nd-pick")
        pg.wait_for_timeout(300)
        check(pg.input_value("input[name='docno[]']") == f"PMO-{year}-0004", "next number 0004")
        pg.click("#nd-blank")
        pg.wait_for_timeout(200)
        pg.locator("input[name='title[]']").nth(1).fill("Notice of Award – Paper copy")
        pg.click(".modal button[type=submit]")
        pg.wait_for_selector(".modal:has-text('already saved as PMO-')")
        check(True, "duplicate file warning")
        pg.click(".modal-back:last-child button[type=submit]")
        pg.wait_for_selector("h1:has-text('Documents')")
        pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 5, "5 documents")
        check(pg.locator("text=paper / no file").count() == 1, "paper document has no file")

        print("== release one -> closed", flush=True)
        pg.locator("tr:has-text('Contractor Billing') button[data-act=route]").click()
        pg.select_option(".modal select[name=action]", "Released")
        check(pg.input_value(".modal input[name=due_date]") == "", "closing clears due date")
        pg.fill(".modal input[name=location]", "Contractor")
        pg.click(".modal button[type=submit]")
        pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 4, "released doc hidden from active list")
        pg.check("#f-closed"); pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 5, "include released shows it")
        pg.uncheck("#f-closed")

        print("== expiry on permit", flush=True)
        pg.click("a:has-text('Building Permit 2026')")
        pg.click("button[data-act=editDoc]")
        pg.select_option(".modal select[name=category]", "Permits & Licenses")
        pg.fill(".modal input[name=expiry_date]", iso(today + datetime.timedelta(days=10)))
        pg.click(".modal button[type=submit]")
        pg.wait_for_selector(".pill-exp.soon")
        check(True, "expiry warning shows")

        print("== dashboard", flush=True)
        pg.click("#nav button[data-view=dashboard]")
        pg.wait_for_selector("text=Where are the documents now?")
        pg.screenshot(path=f"{SHOTS}/05_dashboard.png", full_page=True)
        check(pg.locator(".loc-row:has-text('Mr. Sabanal')").count() == 1, "location summary has Mr. Sabanal")
        check(pg.inner_text("#nav-overdue") == "1", "overdue badge = 1 (Building Permit)")
        pg.click(".loc-row:has-text('Accounting')")
        pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 1 and pg.input_value("#f-location") == "Accounting", "click location filters list")
        pg.fill("#f-search", "permit"); pg.click("button[data-act=clearFilters]"); pg.wait_for_timeout(200)
        pg.fill("#f-search", "permit"); pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 1, "search works")

        print("== prints", flush=True)
        pg.click("#nav button[data-view=reports]")
        pg.select_option("#r-loc", "Mr. Sabanal")
        for act, name in [("printWith", "followup"), ("printOverdue", "overdue"), ("printExpiry", "expiry")]:
            pg.evaluate("window.__printed = null")
            pg.click(f".card button[data-act={act}]")
            pg.wait_for_function("window.__printed")
            out = pg.evaluate("window.__printed")
            p2 = b.new_page(viewport={"width": 800, "height": 1000})
            p2.set_content(f"<html><head><link rel=stylesheet href='{BASE}styles.css'><link rel=stylesheet href='{BASE}dmts.css'><style>body{{padding:30px;background:#fff}}</style></head><body>{out}</body></html>")
            p2.wait_for_timeout(200); p2.screenshot(path=f"{SHOTS}/print_{name}.png", full_page=True); p2.close()
            check(len(out) > 300, f"{act} printed")
        pg.click("#nav button[data-view=register]")
        pg.click("button[data-act=clearFilters]"); pg.wait_for_timeout(200)
        pg.click(f"a.docno:has-text('PMO-{year}-0001')")
        pg.evaluate("window.__printed = null")
        pg.click("button[data-act=printSlip]")
        pg.wait_for_function("window.__printed")
        out = pg.evaluate("window.__printed")
        check("Received by" in out and "Accounting" in out, "tracking slip printed")
        p2 = b.new_page(viewport={"width": 800, "height": 1000})
        p2.set_content(f"<html><head><link rel=stylesheet href='{BASE}styles.css'><style>body{{padding:30px;background:#fff}}</style></head><body>{out}</body></html>")
        p2.wait_for_timeout(200); p2.screenshot(path=f"{SHOTS}/print_slip.png", full_page=True); p2.close()

        print("== exports, activity, backup", flush=True)
        pg.click("#nav button[data-view=reports]")
        pg.click(".card button[data-act=exportDocs]"); pg.wait_for_timeout(300)
        pg.click(".card button[data-act=exportHistory]"); pg.wait_for_timeout(300)
        exs = [c for c in calls() if c["cmd"] == "export_xlsx"]
        check(len(exs) == 2 and all(len(r) == len(c["args"]["headers"]) for c in exs for r in c["args"]["rows"]), "excel exports ok")
        check(len(exs[0]["args"]["rows"]) == 5, "register export includes released")
        pg.click("#nav button[data-view=activity]")
        pg.wait_for_selector("h1:has-text('Activity')")
        pg.screenshot(path=f"{SHOTS}/06_activity.png")
        pg.click("#nav button[data-view=settings]")
        pg.click("button[data-act=backup]")
        pg.wait_for_selector(".toast:has-text('Backup saved')")

        print("== delete (soft)", flush=True)
        pg.click("#nav button[data-view=register]")
        pg.click("a:has-text('Notice of Award')")
        pg.click("button[data-act=delDoc]")
        pg.click(".modal button[type=submit]")
        pg.wait_for_selector("h1:has-text('Documents')"); pg.wait_for_timeout(300)
        check(pg.locator("#doc-table tbody tr").count() == 3, "delete hides document")
        b.close()
finally:
    srv.terminate()

print("\nERRORS:" if errors else "\nALL GOOD", *errors, sep="\n  ")
sys.exit(1 if errors else 0)
